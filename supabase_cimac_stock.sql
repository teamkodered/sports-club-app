alter table public.supplier_stock enable row level security;
drop policy if exists supplier_stock_admin on public.supplier_stock;
create policy supplier_stock_admin on public.supplier_stock for all
  using (exists (select 1 from members where auth_id = (select auth.uid()) and role in ('admin', 'captain', 'coach', 'head_coach', 'leader')))
  with check (exists (select 1 from members where auth_id = (select auth.uid()) and role = 'admin'));
